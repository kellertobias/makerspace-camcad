export function strokeTextToPaths(spec: TextSpec): Path[] {
  const size = Math.max(0.5, spec.size);
  const scale = size / 10;
  const spacing = spec.letterSpacing ?? 0;
  const lines = spec.text.replace(/\r/g, '').split('\n');
  const advance = (ch: string) => (ch === ' ' ? 4 : 7) * scale + spacing;
  const widths = lines.map((line) => Math.max(0, [...line].reduce((w, ch) => w + advance(ch), 0) - (line ? spacing : 0)));
  const maxWidth = Math.max(0, ...widths);
  const result: Path[] = [];
  lines.forEach((line, row) => {
    let x = spec.align === 'right' ? maxWidth - widths[row] : spec.align === 'center' ? (maxWidth - widths[row]) / 2 : 0;
    const y = -row * (spec.lineHeight ?? 1.2) * size;
    for (const ch of line) {
      const [base, extra] = accents[ch] ?? [ch, ''];
      const strokes = [glyphs[base] ?? glyphs['?'], extra].filter(Boolean).join('|');
      for (const stroke of strokes.split('|')) {
        if (!stroke) continue;
        const points: Vec2[] = stroke.split(' ').map((pair) => {
          const [px, py] = pair.split(',').map(Number);
          return { x: x + px * scale, y: y + py * scale };
        });
        if (points.length > 1) result.push({ id: newId('pa'), start: points[0], segs: points.slice(1).map((to) => ({ k: 'L', to })), closed: false, layer: 'Text' });
      }
      x += advance(ch);
    }
  });
  return result;
}
